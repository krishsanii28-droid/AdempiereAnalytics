<#
Installs (or removes) the InsightAI database objects in the ADempiere database.

  powershell -ExecutionPolicy Bypass -File scripts\db_install.ps1              # install / update
  powershell -ExecutionPolicy Bypass -File scripts\db_install.ps1 -Uninstall   # remove everything

The admin connection (host, port, database, user, password) is read from ADempiere's own
AdempiereEnv.properties, so no admin password is stored in this project.
The service role's password is generated once and written to .env, which git ignores.
#>
param(
    [string]$AdempiereHome = $(if ($env:ADEMPIERE_HOME) { $env:ADEMPIERE_HOME } else { 'C:\Adempiere' }),
    [string]$Psql = 'C:\Program Files\PostgreSQL\14\bin\psql.exe',
    [switch]$Uninstall
)
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$envFile = Join-Path $root '.env'

$props = @{}
Get-Content (Join-Path $AdempiereHome 'AdempiereEnv.properties') | Where-Object { $_ -match '^[A-Z_]+=' } | ForEach-Object {
    $k, $v = $_ -split '=', 2
    $props[$k] = $v
}
$dbHost = $props['ADEMPIERE_DB_SERVER']; $dbPort = $props['ADEMPIERE_DB_PORT']; $dbName = $props['ADEMPIERE_DB_NAME']

function Invoke-Psql([string[]]$PsqlArgs) {
    $env:PGPASSWORD = $props['ADEMPIERE_DB_PASSWORD']
    $env:PGCLIENTENCODING = 'UTF8'
    try {
        & $Psql -X -q -h $dbHost -p $dbPort -U $props['ADEMPIERE_DB_USER'] -d $dbName -v ON_ERROR_STOP=1 @PsqlArgs
        if ($LASTEXITCODE -ne 0) { throw "psql failed (exit $LASTEXITCODE)" }
    } finally {
        $env:PGPASSWORD = $null
    }
}

if ($Uninstall) {
    Invoke-Psql @('-1', '-f', (Join-Path $root 'db\99_uninstall.sql'))
    Write-Host "InsightAI schema and roles removed from database $dbName."
    return
}

# Reuse the service password if .env already has one, otherwise generate it.
$password = $null
if (Test-Path $envFile) {
    $line = Get-Content $envFile | Where-Object { $_ -match '^INSIGHTAI_DB_PASSWORD=' } | Select-Object -First 1
    if ($line) { $password = ($line -split '=', 2)[1] }
}
if (-not $password) {
    $bytes = New-Object byte[] 24
    [System.Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($bytes)
    $password = ([Convert]::ToBase64String($bytes)) -replace '[+/=]', 'x'
    $lines = @(
        '# Generated by scripts\db_install.ps1. Do not commit.',
        "INSIGHTAI_DB_HOST=$dbHost",
        "INSIGHTAI_DB_PORT=$dbPort",
        "INSIGHTAI_DB_NAME=$dbName",
        'INSIGHTAI_DB_USER=insightai_ro',
        "INSIGHTAI_DB_PASSWORD=$password"
    )
    [System.IO.File]::WriteAllLines($envFile, $lines)
    Write-Host "Wrote $envFile"
}

Invoke-Psql @('-1', '-f', (Join-Path $root 'db\01_install.sql'))
Invoke-Psql @('-v', "ro_password=$password", '-f', (Join-Path $root 'db\02_login_role.sql'))
Write-Host "InsightAI schema installed in database $dbName. Service login: insightai_ro (password in .env)."
